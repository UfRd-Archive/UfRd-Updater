def test_empty_manifest_forms():
    assert render_manifest({}) == "{}\n"
    assert render_sources_nix({}) == (
        "# Generated by ufrd-updater. Do not edit.\n{ }\n"
    )
    assert render_fetchurl_nix({}) == (
        "# Generated by ufrd-updater. Do not edit.\n{ fetchurl }:\n{ }\n"
    )


def test_nix_escaping():
    assert nix_string('a"b\\c${d}\n\r\t') == '"a\\"b\\\\c\\${d}\\n\\r\\t"'
    manifest = {
        "demo": {
            "x86_64-linux": {
                "version": "1.0",
                "url": "https://example.test/a",
                "filename": 'evil"${x}.tar.gz',
                "hashes": {"sha256-sri": "sha256-x"},
            }
        }
    }
    text = render_sources_nix(manifest)
    assert 'filename = "evil\\"\\${x}.tar.gz";' in text


def test_nix_parse_when_available(tmp_path):
    nix = shutil.which("nix-instantiate")
    if not nix:
        pytest.skip("nix-instantiate is not available")
    sources = tmp_path / "sources.nix"
    fetchurl = tmp_path / "fetchurl.nix"
    sources.write_text(render_sources_nix(SAMPLE_MANIFEST), encoding="utf-8")
    fetchurl.write_text(render_fetchurl_nix(SAMPLE_MANIFEST), encoding="utf-8")
    for path in (sources, fetchurl):
        completed = subprocess.run(
            [nix, "--parse", str(path)], capture_output=True, text=True
        )
        assert completed.returncode == 0, completed.stderr


def test_markdown_redacts_and_truncates_failures():
    from dataclasses import replace

    decision = make_decision(
        entry=replace(
            make_decision().entry,
            source_url="https://example.test/app.tar.gz?token=secret#frag",
        )
    )
    tagged = {"demo/x86_64-linux": make_tagged(decision=decision)}
    error = "x" * 600
    text = render_update_md(
        run=fixed_run(),
        tagged=tagged,
        failures=[
            Failure("demo", "aarch64-linux", error),
            Failure("demo", "x86_64-linux", "see https://example.test/x?token=secret"),
        ],
        archive_enabled=False,
        repository="org/UfRd-Archive",
    )
    assert "2026-10-23 15:30:12 UTC" in text
    assert "secret" not in text
    assert "token" not in text
    assert r"https\:\/\/example\.test\/app\.tar\.gz" in text
    assert "| Change |" in text
    assert "## Failures" in text
    assert "x" * 500 in text
    assert "x" * 501 not in text


def test_markdown_data_cells_display_html_entities_and_markup_literally():
    literal = "<b>&copy; `code` [link](x) *em* _em_ ~s~ $m$ \\ |</b>"
    escaped = (
        r"&lt;b&gt;&amp;copy\; \`code\` \[link\]\(x\) "
        r"\*em\* \_em\_ \~s\~ \$m\$ \\ \|&lt;\/b&gt;"
    )
    decision = make_decision(
        entry=make_entry(version=literal, filename=literal),
        baseline={"version": literal},
    )
    text = render_update_md(
        run=fixed_run(),
        tagged={decision.key: make_tagged(decision=decision)},
        failures=[Failure(literal, literal, literal)],
        archive_enabled=False,
        repository=literal,
    )
    assert text.count(escaped) == 7
    assert "<b>" not in text
    assert "&copy;" not in text
    assert "`code`" not in text


@pytest.mark.parametrize("scheme", ["https", "HTTPS"])
@pytest.mark.parametrize("archive_enabled", [False, True])
def test_markdown_redacts_complete_known_urls(scheme, archive_enabled):
    url = f"{scheme}://user:private@example.test/a)b?token=secret)tail#fragment"
    decision = make_decision(entry=make_entry(source_url=url))
    text = render_update_md(
        run=fixed_run(),
        tagged={decision.key: make_tagged(decision=decision, archive_url=url)},
        failures=[],
        archive_enabled=archive_enabled,
        repository="org/UfRd-Archive",
    )
    assert r"example\.test" in text
    for sensitive in ("private", "secret", "token", "tail", "fragment"):
        assert sensitive not in text


