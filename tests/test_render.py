def test_write_atomic_replaces_and_cleans(tmp_path):
    path = tmp_path / "out" / "file.txt"
    write_atomic(path, "one\n")
    write_atomic(path, "two\n")
    assert path.read_text(encoding="utf-8") == "two\n"
    assert [item.name for item in path.parent.iterdir()] == ["file.txt"]
