SAMPLE_MANIFEST = {
    "wechat": {
        "x86_64-windows": {
            "hashes": abc_hashes(),
            "filename": "WeChatSetup.exe",
            "url": "https://example.test/WeChatSetup.exe",
            "version": "3.9.12",
        }
    }
}


def test_manifest_json_field_order_and_format():
    text = render_manifest(SAMPLE_MANIFEST)
    assert text.endswith("\n")
    parsed = json.loads(text)
    assert list(parsed) == ["wechat"]
    assert list(parsed["wechat"]) == ["x86_64-windows"]
    entry = parsed["wechat"]["x86_64-windows"]
    assert list(entry) == ["version", "url", "filename", "hashes"]
    assert list(entry["hashes"])[:3] == ["md5", "md5-nix32", "md5-sri"]
    assert list(entry["hashes"])[-3:] == ["sha512", "sha512-nix32", "sha512-sri"]
    assert entry["hashes"] == abc_hashes()
    assert text == json.dumps(parsed, indent=2, ensure_ascii=False) + "\n"


