import os
import string
import uuid
from pathlib import Path
from typing import Any

from .hashes import HASH_KEYS
from .http import redact_text, redact_url
from .manifest import Manifest
from .model import Failure, RunContext
from .release import TaggedEntry

NIX_HEADER = "# Generated by ufrd-updater. Do not edit.\n"
MARKDOWN_ESCAPES = str.maketrans(
    {char: f"\\{char}" for char in string.punctuation if char not in "&<>"}
)


def _ordered_hashes(hashes: dict[str, str]) -> dict[str, str]:
    ordered = {key: hashes[key] for key in HASH_KEYS if key in hashes}
    for key in sorted(hashes):
        if key not in ordered:
            ordered[key] = hashes[key]
    return ordered


def render_manifest(manifest: Manifest) -> str:
    ordered: dict[str, dict[str, dict[str, Any]]] = {}
    for target in sorted(manifest):
        ordered[target] = {}
        for arch in sorted(manifest[target]):
            entry = manifest[target][arch]
            ordered[target][arch] = {
                "version": entry["version"],
                "url": entry["url"],
                "filename": entry["filename"],
                "hashes": _ordered_hashes(entry["hashes"]),
            }
    return json.dumps(ordered, indent=2, ensure_ascii=False) + "\n"


def nix_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\")
    escaped = escaped.replace('"', '\\"')
    escaped = escaped.replace("\n", "\\n")
    escaped = escaped.replace("\r", "\\r")
    escaped = escaped.replace("\t", "\\t")
    escaped = escaped.replace("${", "\\${")
    return f'"{escaped}"'


def render_sources_nix(manifest: Manifest) -> str:
    lines = [NIX_HEADER.rstrip("\n")]
    if not manifest:
        lines.append("{ }")
        return "\n".join(lines) + "\n"
    lines.append("{")
    for target in sorted(manifest):
        lines.append(f"  {nix_string(target)} = {{")
        for arch in sorted(manifest[target]):
            entry = manifest[target][arch]
            lines.append(f"    {nix_string(arch)} = {{")
            lines.append(f"      version = {nix_string(entry['version'])};")
            lines.append(f"      url = {nix_string(entry['url'])};")
            lines.append(f"      filename = {nix_string(entry['filename'])};")
            lines.append("      hashes = {")
            for key, value in _ordered_hashes(entry["hashes"]).items():
                lines.append(f"        {nix_string(key)} = {nix_string(value)};")
            lines.append("      };")
            lines.append("    };")
        lines.append("  };")
    lines.append("}")
    return "\n".join(lines) + "\n"


def render_fetchurl_nix(manifest: Manifest) -> str:
    lines = [NIX_HEADER.rstrip("\n"), "{ fetchurl }:"]
    if not manifest:
        lines.append("{ }")
        return "\n".join(lines) + "\n"
    lines.append("{")
    for target in sorted(manifest):
        lines.append(f"  {nix_string(target)} = {{")
        for arch in sorted(manifest[target]):
            entry = manifest[target][arch]
            lines.append(f"    {nix_string(arch)} = fetchurl {{")
            lines.append(f"      url = {nix_string(entry['url'])};")
            lines.append(
                f"      hash = {nix_string(entry['hashes'].get('sha256-sri', ''))};"
            )
            lines.append("    };")
        lines.append("  };")
    lines.append("}")
    return "\n".join(lines) + "\n"


def _cell(value: Any) -> str:
    text = "" if value is None else str(value)
    text = text.replace("\r", " ").replace("\n", " ")
    return html.escape(text.translate(MARKDOWN_ESCAPES), quote=False)


def render_update_md(
    *,
    run: RunContext,
    tagged: dict[str, TaggedEntry],
    failures: list[Failure],
    archive_enabled: bool,
    repository: str,
) -> str:
    lines = [
        f"# UfRd update {run.datetime.strftime('%Y-%m-%d %H:%M:%S')} UTC",
        "",
    ]
    tags = sorted({item.tag for item in tagged.values()})
    tag_text = ", ".join(f"`{tag}`" for tag in tags) if tags else "none"
    lines.append(f"- Tag(s): {tag_text}")
    lines.append(f"- Archive: {'enabled' if archive_enabled else 'disabled'}")
    lines.append(f"- Repository: {_cell(repository) if repository else 'none'}")
    lines.append("")

    if not tagged and not failures:
        lines.append("No updates.")
        return "\n".join(lines) + "\n"

    if tagged:
        lines.extend(
            [
                "## Changes",
                "",
                "| Target | Arch | Change | Old version | New version | Filename | URL | SHA256 SRI |",
                "| --- | --- | --- | --- | --- | --- | --- | --- |",
            ]
        )
        for key in sorted(tagged):
            item = tagged[key]
            decision = item.decision
            baseline = decision.baseline
            url = (
                item.archive_url
                if archive_enabled and item.archive_url
                else decision.entry.source_url
            )
            lines.append(
                "| "
                + " | ".join(
                    [
                        _cell(decision.entry.target),
                        _cell(decision.entry.arch),
                        _cell(decision.kind),
                        _cell(baseline["version"] if baseline else "-"),
                        _cell(decision.entry.version),
                        _cell(decision.entry.filename),
                        _cell(redact_url(url)),
                        _cell(item.hashes["sha256-sri"]),
                    ]
                )
                + " |"
            )
        lines.append("")

    if failures:
        lines.extend(
            [
                "## Failures",
                "",
                "| Target | Arch | Error |",
                "| --- | --- | --- |",
            ]
        )
        for failure in failures:
            lines.append(
                "| "
                + " | ".join(
                    [
                        _cell(failure.target),
                        _cell(failure.arch),
                        _cell(redact_text(failure.error)[:500]),
                    ]
                )
                + " |"
            )
        lines.append("")
    return "\n".join(lines)


def write_atomic(path: Path, text: str) -> None:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(f".{path.name}.tmp-{os.getpid()}-{uuid.uuid4().hex}")
    try:
        with open(temporary, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
        os.replace(temporary, path)
    except BaseException:
        try:
            temporary.unlink()
        except OSError:
            pass
        raise
